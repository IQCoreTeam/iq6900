const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const { JSDOM } = require('jsdom');
const jquery = require('jquery');
const root = path.resolve(__dirname, '..');
const baseline = process.argv.includes('--baseline');
const template = fs.readFileSync(baseline ? path.resolve(root, '../nft_launch.html') : path.join(root, 'assets/html/sections/nft_launch.html'), 'utf8');
const script = fs.readFileSync(baseline ? path.resolve(root, '../nft_launch.js') : path.join(root, 'assets/js/sections/pages/nft_launch.js'), 'utf8');
test('single inscription action identifies the NFT flow and retains wallet guards', async () => {
  const dom = new JSDOM('<main id="main_section"></main>', { url: 'https://example.test/?menu=nft&single=test-inscription', runScripts: 'outside-only' });
  const { window } = dom;
  const $ = jquery(window);
  window.$ = window.jQuery = $;
  window.console.log = () => {};
  let requestedTemplate;
  $.get = (url, done) => { requestedTemplate = url; done(template); };
  const reads = [];
  window.iqNftReady = true;
  window.iqNft = { nftApi: () => 'https://nft.iqlabs.dev', api: async () => ({status:200,json:{ok:true}}), readRow: async (C) => { reads.push(C); return { who: 'owner-wallet', kind: 'text', body: 'inscribed content' }; } };
  window.eval(script);
  const page = $.nft_launch;
  page.wireNav = () => {};
  page.init();
  await new Promise((resolve) => setImmediate(resolve));
  assert.deepEqual(reads, ['test-inscription'], 'single query routes to the inscription reader');
  assert.equal($('#nftl_single').css('display') === 'none', false);
  assert.equal($('#nftl_single .wh > span').last().text(), 'make_it_an_nft.exe');
  assert.equal($('#nftl_single .cright > .lab').text(), '// MAKE IT AN NFT');
  assert.equal($('#nftl_nav_mid').text(), '// MAKE IT AN NFT');
  assert.equal($('#nftl_stext').text(), 'inscribed content');
  assert.equal($('#nftl_sstate button').text(), 'CONNECT WALLET');
  page.wallet = 'owner-wallet';
  let minted = 0;
  page.mintSingle = () => { minted++; };
  page.singleState('idle');
  assert.equal($('#nftl_sstate button').text(), 'MAKE IT AN NFT · SIGN IN WALLET');
  $('#nftl_sstate button').trigger('click');
  assert.equal(minted, 1, 'NFT action retains its mintSingle handler');
  page.wallet = 'other-wallet';
  page.singleState('idle');
  assert.equal($('#nftl_sstate button').length, 0, 'non-owner cannot mint');
  assert.match($('#nftl_sstate').text(), /only the owner/);
  assert.match(requestedTemplate, /nft_launch\.html\?ver=28-nft-sharing-20261101$/);
  const index = fs.readFileSync(path.join(root, 'assets/index.html'), 'utf8');
  assert.match(index, /nft_launch\.js\?ver=41-nft-sharing-20261101/);
  dom.window.close();
  console.log('PASS single NFT deep-link labels, signed-out/owner/non-owner states, mint handler, and cache versions');
});
